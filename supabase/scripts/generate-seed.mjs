// Generates supabase/migrations/20260101000006_reference_data.sql from ../../reference-data.
// Usage: node supabase/scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const refDir = join(here, '..', '..', 'reference-data');
const out = join(here, '..', 'migrations', '20260101000006_reference_data.sql');
const load = (name) => JSON.parse(readFileSync(join(refDir, name), 'utf8'));

const competencies = load('competencies.json');
const targets = load('targets.json');
const templates = load('templates.json');
const documents = load('documents.json');

const lit = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => `$json$${JSON.stringify(v)}$json$::jsonb`;

const lines = [];
lines.push('-- GENERATED by supabase/scripts/generate-seed.mjs from /reference-data. Do not edit by hand.');
lines.push('-- Institutional reference data: competencies, targets (v1), form templates, academic documents.');
lines.push('');
lines.push('insert into public.institution_settings (id) values (1) on conflict (id) do nothing;');
lines.push('');

lines.push('insert into public.competencies (code, title, domain, progression, sort_order) values');
lines.push(
  competencies.competencies
    .map((c, i) => `  (${lit(c.code)}, ${lit(c.title)}, ${lit(c.domain)}, ${lit(c.progression ?? 'PS → PI')}, ${i + 1})`)
    .join(',\n') +
    '\non conflict (code) do update set title = excluded.title, domain = excluded.domain, progression = excluded.progression, sort_order = excluded.sort_order;',
);
lines.push('');

const targetNotes = (t) =>
  [t.distribution && `Distribution: ${t.distribution}`, t.documentation && `Documentation: ${t.documentation}`, t.levelRemarks && `Level/remarks: ${t.levelRemarks}`]
    .filter(Boolean)
    .join('; ') || null;

const targetRows = [
  ...targets.exposure.map((t, i) => ({ ...t, category: 'EXPOSURE', sort: i + 1 })),
  ...targets.procedures.map((t, i) => ({ ...t, category: 'PROCEDURE', sort: 100 + i + 1 })),
];
lines.push('insert into public.targets (key, category, label, target_value, sort_order, version, is_current, notes) values');
lines.push(
  targetRows
    .map((t) => `  (${lit(t.key)}, ${lit(t.category)}, ${lit(t.label)}, ${t.target}, ${t.sort}, 1, true, ${lit(t.notes ?? targetNotes(t))})`)
    .join(',\n') + '\non conflict (key, version) do nothing;',
);
lines.push('');

const schemaOf = (t) => ({ ...t, roleOptions: templates.roleOptions });
lines.push('insert into public.form_templates (code, category, title, subtitle, schema, required_initial, period_count, version, sort_order) values');
lines.push(
  templates.templates
    .map(
      (t) =>
        `  (${lit(t.code)}, ${lit(t.category)}, ${lit(t.title)}, ${lit(t.subtitle ?? null)}, ${json(schemaOf(t))}, ` +
        `${t.requiredInitial ?? 0}, ${t.periodCount ?? 'null'}, ${t.version ?? 1}, ${t.sortOrder ?? 0})`,
    )
    .join(',\n') +
    '\non conflict (code) do update set category = excluded.category, title = excluded.title, subtitle = excluded.subtitle,' +
    ' schema = excluded.schema, required_initial = excluded.required_initial, period_count = excluded.period_count,' +
    ' version = excluded.version, sort_order = excluded.sort_order;',
);
lines.push('');

for (const d of documents.documents) {
  lines.push(
    `insert into public.academic_documents (code, title, description, sort_order) values (${lit(d.code)}, ${lit(d.title)}, ${lit(d.description)}, ${d.sortOrder ?? 0}) on conflict (code) do nothing;`,
  );
  lines.push(
    `insert into public.document_versions (document_id, version_no, content, notes, published, published_at)\n` +
      `select id, 1, ${json(d.content)}, 'Initial institutional version', true, now() from public.academic_documents where code = ${lit(d.code)}\n` +
      `on conflict (document_id, version_no) do nothing;`,
  );
}
lines.push('');
lines.push(`comment on table public.targets is ${lit(targets.disclaimer)};`);

writeFileSync(out, lines.join('\n') + '\n', 'utf8');
console.log(`Wrote ${out}`);
